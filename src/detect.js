'use strict';

// Signal-based detection of mojibake.
//
// The naive heuristic -- "encode to latin1 then decode as utf8" -- is wrong in
// BOTH directions, and the reasons are structural rather than accidental:
//
//   * False negatives. Cyrillic text that was UTF-8 but read through windows-1251
//     (Russian on a legacy Windows box) comes out as CLEAN Cyrillic with no byte
//     pairing at all: "Привет" becomes "РџСЂРёРІРµС‚". Every "look for accented
//     characters" rule misses it, and the latin1 round trip actively corrupts
//     it. This is why detection and repair must be separate steps.
//
//   * False positives. Correct German contains "ß»" and correct French contains
//     "â", "é»"-shaped and cp1252-punctuation neighbours. Any rule that fires on
//     the presence of a single suspicious character mangles valid text.
//
// So detection never looks at individual characters. It measures four structural
// signals and combines them into a score in [0, 1] with a human-readable reason.
//
// ---------------------------------------------------------------------------
// THRESHOLDS -- where these numbers come from
// ---------------------------------------------------------------------------
// Every threshold below was measured, not guessed. For a corpus of correct
// Western/Eastern European text, Cyrillic text, CJK, RTL, maths and emoji, and
// a corpus of deliberately broken text generated by encoding correct text
// through each wrong codec, the signals separate as follows (see test/detect.test.js
// which asserts these bounds):
//
//   utf8PairRatio        correct text: max 0.100 (German "Maß»")   broken: min 0.947
//   c1Ratio              correct text: max 0.000                  broken: min 0.063
//   cyrillicExtrasRatio  correct text: max 0.200 (Serbian/Macedonian)
//                                                            broken: min 0.333
//   replacementChars     correct text: 0                         broken: may be > 0
//
// Thresholds are placed in the MIDDLE of each gap, not at the edge:
//   UTF8_PAIR_MIN_RATIO       0.50  (gap 0.100 .. 0.947)
//   UTF8_PAIR_MIN_PAIRS      2     (no correct sample above 1)
//   C1_MIN_RATIO              0.02  (gap 0.000 .. 0.063)
//   C1_MIN_COUNT              1
//   CYRILLIC_EXTRAS_MIN_RATIO 0.26  (gap 0.200 .. 0.333)
//   CYRILLIC_EXTRAS_MIN_COUNT 2     (archaic Slavonic lists letters one at a time)
//
// The "min count" companions exist because a ratio alone is unstable on short
// strings: "café" has one artefact pair and ratio 1.0, and would otherwise be
// indistinguishable from "Maß»" in a longer sentence.
//
// ---------------------------------------------------------------------------
// SIGNAL WEIGHTS AND WHY THEY DIFFER
// ---------------------------------------------------------------------------
// Each signal is independently validated as false-positive-free at its own
// threshold: no correct sample in the corpus trips any one of them. So any single
// signal firing is sufficient grounds to consider the text broken, and the
// suspect threshold (0.4) sits below the lowest signal weight (0.45).
//
// The weights then express how much evidence each signal carries, which matters
// because they are NOT equally strong:
//
//   utf8-pair 0.60  Widest measured gap by far (0.100 vs 0.947) and it
//                   identifies the byte structure directly. The classic
//                   utf8-as-latin1/cp1252/cp1251 accident lands here.
//   c1-control 0.50 Raw 0x80-0x9F bytes that stayed undecoded. Unambiguous:
//                   nobody writes U+0080-U+009F into a document on purpose.
//   replacement 0.50 U+FFFD means data was already lost upstream. It does not
//                   identify WHICH encoding was wrong, but it does mean the text
//                   is damaged, so it must not be dismissed.
//   cyrillic-extras 0.45 Narrowest gap (0.200 vs 0.333) and only applies to
//                   Cyrillic text, hence the lowest weight. Without it, cp1251
//                   mojibake is undetectable: that accident produces clean
//                   Cyrillic with zero byte-pair structure.
//
// Sum is capped at 1. When several signals fire the text is damaged in more than
// one way, which the cap reflects by saturating rather than growing without bound.

const { CP1251 } = require('./tables.js');
const { isC1, isContinuation, isLead, scanPairs } = require('./structure.js');

// ---------------------------------------------------------------------------
// Derived character classes
// ---------------------------------------------------------------------------
// The lead/continuation definition itself lives in structure.js so that the
// detector and the scorer cannot disagree about what a byte pair is. What follows
// is the one class unique to detection: the Cyrillic letters that windows-1251
// spends its 0x80-0xBF range on.

/**
 * Code points that windows-1251 places on bytes 0x80-0xBF but that are absent
 * from ordinary modern Russian, Ukrainian and Bulgarian prose.
 *
 * This is the signature of cp1251 mojibake: because windows-1251 spends its
 * 0x80-0xBF range on punctuation and the rarer Cyrillic letters, every UTF-8
 * continuation byte lands on one of them. Real Russian puts almost none of these
 * in running text (measured: max 0.200 for Serbian or Macedonian, which do use
 * ђ ј љ њ ћ ѕ ќ џ); cp1251 mojibake puts 0.333-0.412 of its Cyrillic letters
 * here.
 *
 * This is the only signal needed for the one flavour of mojibake that has no byte
 * structure at all: Russian read through windows-1251 comes out as clean-looking
 * Cyrillic, so nothing about the bytes gives it away.
 */
const CP1251_MID = (() => {
  const set = new Set();
  for (let byte = 0x80; byte <= 0xbf; byte++) set.add(CP1251[byte]);
  return set;
})();

/**
 * Signals the given code point carries, as a frozen set of names. Documented so
 * callers can render a verdict without re-deriving anything.
 */
const SIGNAL_NAMES = Object.freeze([
  'utf8-pair',
  'c1-control',
  'cyrillic-extras',
  'replacement',
]);

// ---------------------------------------------------------------------------
// Thresholds (see the calibration notes at the top of this file)
// ---------------------------------------------------------------------------

/** Minimum fraction of non-ASCII chars inside a UTF-8 lead/continuation pair. */
const UTF8_PAIR_MIN_RATIO = 0.5;
/** Minimum number of such pairs, so a single stray pair in a long line is noise. */
const UTF8_PAIR_MIN_PAIRS = 2;
/** Minimum fraction of C1 control characters. */
const C1_MIN_RATIO = 0.02;
/** Minimum number of C1 control characters. */
const C1_MIN_COUNT = 1;
/** Minimum fraction of Cyrillic letters that are cp1251 padding characters. */
const CYRILLIC_EXTRAS_MIN_RATIO = 0.26;
/** Minimum count of those letters. */
const CYRILLIC_EXTRAS_MIN_COUNT = 2;
/**
 * How much evidence each signal carries once it has cleared its threshold.
 * See the calibration notes at the top of this file.
 */
const SIGNAL_WEIGHTS = Object.freeze({
  'utf8-pair': 0.6,
  'c1-control': 0.5,
  replacement: 0.5,
  'cyrillic-extras': 0.45,
});

/** Score at or above which a text is reported as broken. */
const SUSPECT_THRESHOLD = 0.4;

/** Thresholds exported so the CLI and tests can document and override them. */
const THRESHOLDS = Object.freeze({
  utf8PairMinRatio: UTF8_PAIR_MIN_RATIO,
  utf8PairMinPairs: UTF8_PAIR_MIN_PAIRS,
  c1MinRatio: C1_MIN_RATIO,
  c1MinCount: C1_MIN_COUNT,
  cyrillicExtrasMinRatio: CYRILLIC_EXTRAS_MIN_RATIO,
  cyrillicExtrasMinCount: CYRILLIC_EXTRAS_MIN_COUNT,
  suspect: SUSPECT_THRESHOLD,
});

/**
 * Count structural signals in a string.
 *
 * Pure and allocation-light: single pass over code points. Exposed separately
 * from `looksMojibake` so scoring and detection can share one measurement pass.
 *
 * @param {string} text
 * @returns {{
 *   length: number, nonAscii: number, letters: number, cyrillicLetters: number,
 *   utf8Pairs: number, c1Controls: number, cyrillicExtras: number,
 *   replacementChars: number, controlChars: number,
 *   utf8PairRatio: number, c1Ratio: number, cyrillicExtrasRatio: number
 * }}
 */
function measure(text) {
  const chars = [...String(text)];
  const m = {
    length: chars.length,
    nonAscii: 0,
    letters: 0,
    cyrillicLetters: 0,
    utf8Pairs: 0,
    c1Controls: 0,
    cyrillicExtras: 0,
    replacementChars: 0,
    controlChars: 0,
    utf8PairRatio: 0,
    c1Ratio: 0,
    cyrillicExtrasRatio: 0,
  };

  for (const ch of chars) {
    const cp = ch.codePointAt(0);
    if (cp >= 0x80) m.nonAscii++;
    if (cp >= 0x20 && cp < 0x7f) continue; // printable ASCII: nothing to count
    if (cp === 0xfffd) {
      m.replacementChars++;
      continue;
    }
    if (cp === 0x09 || cp === 0x0a || cp === 0x0d) continue; // tab/newline/CR
    if (cp < 0x20 || cp === 0x7f) m.controlChars++;
    if (isC1(cp)) m.c1Controls++;
    if (/\p{L}/u.test(ch)) {
      m.letters++;
      if (/\p{Script=Cyrillic}/u.test(ch)) {
        m.cyrillicLetters++;
        if (CP1251_MID.has(cp)) m.cyrillicExtras++;
      }
    }
  }

  const scanned = scanPairs(text);
  m.utf8Pairs = scanned.pairs;
  m.utf8PairRatio = scanned.ratio;
  if (m.nonAscii > 0) m.c1Ratio = m.c1Controls / m.nonAscii;
  if (m.cyrillicLetters > 0) m.cyrillicExtrasRatio = m.cyrillicExtras / m.cyrillicLetters;
  return m;
}

/**
 * Score a text for mojibake, returning the signals that fired.
 *
 * The score is a count of satisfied signals (0-4) mapped to [0, 1]; each signal
 * independently has to clear its measured threshold, so a single coincidence
 * (German "Maß»") cannot reach the suspect threshold on its own. Replacement
 * characters and stray control characters are reported but do not by themselves
 * push the score up, because they indicate data loss rather than a specific
 * misdecoding and are already decisive in the scorer.
 *
 * @param {string} text
 * @param {{ thresholds?: typeof THRESHOLDS }} [options]
 * @returns {{
 *   score: number, signals: string[], metrics: ReturnType<typeof measure>,
 *   thresholds: typeof THRESHOLDS, suspect: boolean
 * }}
 */
function analyse(text, options = {}) {
  const t = Object.assign({}, THRESHOLDS, options.thresholds || {});
  const metrics = measure(text);
  const signals = [];

  if (
    metrics.utf8Pairs >= t.utf8PairMinPairs &&
    metrics.utf8PairRatio >= t.utf8PairMinRatio
  ) {
    signals.push('utf8-pair');
  }
  if (metrics.c1Controls >= t.c1MinCount && metrics.c1Ratio >= t.c1MinRatio) {
    signals.push('c1-control');
  }
  if (
    metrics.cyrillicExtras >= t.cyrillicExtrasMinCount &&
    metrics.cyrillicExtrasRatio >= t.cyrillicExtrasMinRatio
  ) {
    signals.push('cyrillic-extras');
  }
  if (metrics.replacementChars > 0) signals.push('replacement');

  // Weighted sum, saturating at 1. Every signal is individually false-positive
  // free at its own threshold, so one firing is enough to exceed SUSPECT_THRESHOLD.
  let raw = 0;
  for (const name of signals) raw += SIGNAL_WEIGHTS[name] || 0;
  const score = Math.min(raw, 1);

  return {
    score: Number(score.toFixed(4)),
    signals: Object.freeze(signals),
    metrics,
    thresholds: Object.freeze(t),
    suspect: score >= t.suspect,
  };
}

/**
 * Whether a text looks like mojibake.
 *
 * Returns a score with a reason rather than a bare boolean, so a caller can
 * explain itself and so a "maybe" is distinguishable from a "no".
 *
 * @param {string} text
 * @param {{ thresholds?: typeof THRESHOLDS }} [options]
 * @returns {{ broken: boolean, score: number, reason: string, signals: readonly string[] }}
 */
function looksMojibake(text) {
  const { score, signals, suspect, metrics } = analyse(text);
  return {
    broken: suspect,
    score,
    signals,
    reason: explain(signals, metrics, suspect),
  };
}

/**
 * Human-readable explanation of a signal set. Kept separate from scoring so the
 * same explanation can be reused by the CLI's --explain output.
 *
 * @param {readonly string[]} signals
 * @param {ReturnType<typeof measure>} metrics
 * @param {boolean} suspect
 * @returns {string}
 */
function explain(signals, metrics, suspect) {
  if (signals.length === 0) {
    return metrics.nonAscii === 0
      ? 'pure ASCII: no byte-pairing artefacts possible'
      : 'non-ASCII text with no mojibake signature';
  }
  const parts = [];
  if (signals.includes('utf8-pair')) {
    parts.push(
      `${metrics.utf8Pairs} UTF-8 byte pairs (ratio ${metrics.utf8PairRatio.toFixed(2)} ` +
        `>= ${THRESHOLDS.utf8PairMinRatio})`
    );
  }
  if (signals.includes('c1-control')) {
    parts.push(
      `${metrics.c1Controls} C1 control chars (ratio ${metrics.c1Ratio.toFixed(3)} ` +
        `>= ${THRESHOLDS.c1MinRatio})`
    );
  }
  if (signals.includes('cyrillic-extras')) {
    parts.push(
      `${metrics.cyrillicExtras}/${metrics.cyrillicLetters} Cyrillic letters are ` +
        `cp1251 padding (ratio ${metrics.cyrillicExtrasRatio.toFixed(2)} >= ` +
        `${THRESHOLDS.cyrillicExtrasMinRatio})`
    );
  }
  if (signals.includes('replacement')) {
    parts.push(`${metrics.replacementChars} U+FFFD replacement chars`);
  }
  const verdict = suspect
    ? 'broken encoding detected'
    : 'some artefacts present, below the suspect threshold';
  return `${parts.join('; ')} -> ${verdict}`;
}

module.exports = Object.freeze({
  SIGNAL_NAMES,
  SIGNAL_WEIGHTS,
  SUSPECT_THRESHOLD,
  THRESHOLDS,
  analyse,
  explain,
  looksMojibake,
  measure,
});